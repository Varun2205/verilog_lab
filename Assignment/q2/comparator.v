module comparator(input [3:0] a,
                  input [3:0] b,
                  output gt,ls,eq);

assign eq = (a[3] ~^ b[3]) & (a[2] ~^ b[2]) & (a[1] ~^ b[1]) & (a[0] ~^ b[0]);

assign gt = (a[3] & ~b[3]) | ((a[3] ~^ b[3]) & a[2] & ~b[2]) | ((a[3] ~^ b[3]) & (a[2] ~^ b[2]) & a[1] & ~b[1]) | ((a[3] ~^ b[3]) & (a[2] ~^ b[2]) & (a[1] ~^ b[1]) & a[0] & ~b[0]);

assign ls = (~a[3] & b[3]) | ((a[3] ~^ b[3]) & ~a[2] & b[2]) | ((a[3] ~^ b[3]) & (a[2] ~^ b[2]) & ~a[1] & b[1]) | ((a[3] ~^ b[3]) & (a[2] ~^ b[2]) & (a[1] ~^ b[1]) & ~a[0] & b[0]);
endmodule